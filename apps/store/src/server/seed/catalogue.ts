export const SIZES = ['XS', 'S', 'M', 'L', 'XL', 'XXL'] as const;

export interface VariantSeed {
  sku: string;
  fit: Fit;
  colour: string;
  size: string;
  pricePaise: number;
}

export function variantsFor(design: DesignSeed): VariantSeed[] {
  return FITS.flatMap((fit) =>
    COLOURS.flatMap((colour) =>
      SIZES.map((size) => ({
        sku: `SG-${design.code}-${fit.code}-${colour.code}-${size}`,
        fit: fit.fit,
        colour: colour.colour,
        size,
        pricePaise: fit.pricePaise,
      })),
    ),
  );
}

/** Artwork is generated by the storefront (T-05); this is where it will be served. */
export function artworkUrlFor(design: DesignSeed): string {
  return `/artwork/${design.slug}.svg`;
}
